/**
 * Roll the numbered migrations into one runnable script.
 *
 * The migrations are the source of truth and must run in order; a web SQL
 * editor makes running seven files in order the most error-prone step in the
 * whole setup, and a missed one fails silently weeks later. This produces a
 * single paste that cannot be applied out of order because there is no order
 * left to get wrong.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "supabase/migrations";
const files = readdirSync(DIR).filter((f) => /^\d+.*\.sql$/.test(f)).sort();

const head = `-- Squirrel — the whole schema, in one script.
--
-- Generated by \`npm run schema:bundle\` from supabase/migrations/. Paste this
-- into the Supabase SQL editor of a NEW project and the database is ready:
-- tables, row-level security, the plan limits that actually enforce the tiers,
-- sync, billing, and calendar links.
--
-- First run only. This creates tables and types, so running it against a
-- database that already has them fails — the guard below says so in one
-- sentence rather than leaving you to read a wall of "already exists". To
-- apply a later change to a live database, run that numbered migration alone.
--
-- Do not edit this file — it is regenerated. Change the numbered migration.

do $$
begin
  if exists (select 1 from information_schema.tables
             where table_schema = 'public' and table_name = 'profiles') then
    raise exception
      'Squirrel schema is already installed. Run the individual migration you need from supabase/migrations/ instead of this bundle.';
  end if;
end $$;
`;

const body = files
  .map((f) => `\n-- ${"=".repeat(70)}\n-- ${f}\n-- ${"=".repeat(70)}\n\n${readFileSync(join(DIR, f), "utf8").trim()}\n`)
  .join("\n");

writeFileSync("supabase/schema.sql", `${head}\n${body}`);
console.log(`Bundled ${files.length} migrations into supabase/schema.sql`);
